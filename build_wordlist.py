    remote_words = load_remote_words()
    # Les mots de secours restent inclus : ils garantissent quelques entrées
    # même si les sources distantes changent ou deviennent indisponibles.
    words = load_gamer_words() + remote_words + load_fallback_words()
    by_len = build_wordlist(words)
    unique_words = list(dict.fromkeys(words))
    language_model = build_local_language_model(unique_words)

