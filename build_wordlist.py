def normalize_word(word: str, min_length: int = 3) -> str | None:
    if not word:
        return None
    cleaned = unicodedata.normalize("NFKD", word).upper()
    cleaned = "".join(ch for ch in cleaned if not unicodedata.combining(ch))
    cleaned = re.sub(r"[^A-Z]", "", cleaned)
    if len(cleaned) < min_length or len(cleaned) > 15:
        return None
    return cleaned


def load_remote_words() -> list[str]:
    words: list[str] = []
    seen: set[str] = set()

    for url in SOURCE_URLS:
        source_count = 0
        try:
            request = urllib.request.Request(
                url,
                headers={"User-Agent": "Mozilla/5.0"},
            )
            with urllib.request.urlopen(request, timeout=15) as response:
                raw = response.read().decode("utf-8", errors="ignore")
        except (urllib.error.URLError, TimeoutError, ValueError):
            continue

        is_json_source = url.endswith(".json")
        if is_json_source:
            try:
                source_words = json.loads(raw)
            except json.JSONDecodeError:
                continue
            if not isinstance(source_words, list):
                continue
            lines = source_words
        else:
            lines = raw.splitlines()

        for line in lines:
            pieces = (
                [line]
                if is_json_source and isinstance(line, str)
                else re.split(r"[^A-ZÀÂÄÉÈÊËÎÏÔÖÙÛÜÇa-zàâäéèêëîïôöùûüç]+", line)
                if isinstance(line, str)
                else []
            )
            for piece in pieces:
                if not piece:
                    continue
                word = normalize_word(piece)
                if word and word not in seen:
                    seen.add(word)
                    words.append(word)
                    source_count += 1
                    if source_count >= MAX_WORDS_PER_SOURCE or len(words) >= MAX_TOTAL_WORDS:
                        break

            if len(words) >= MAX_TOTAL_WORDS:
                break

    return words


def load_fallback_words() -> list[str]:
    words: list[str] = []
    for raw in FALLBACK_WORDS.split():
        word = normalize_word(raw)
        if word:
            words.append(word)
    return words


def load_gamer_words() -> list[str]:
    words: list[str] = []
    for raw in GAMER_WORDS.split():
        word = normalize_word(raw, min_length=2)
        if word:
            words.append(word)
    return words


def build_wordlist(words: list[str]) -> dict[str, list[dict[str, object]]]:
    unique_words = list(dict.fromkeys(words))
    by_len: dict[str, list[dict[str, object]]] = {}

    for index, word in enumerate(unique_words):
        length = str(len(word))
        by_len.setdefault(length, []).append({
            "word": word,
            "freq": len(unique_words) - index,
        })

    for length in by_len:
        by_len[length].sort(key=lambda entry: -entry["freq"])

    return by_len


def build_local_language_model(words: list[str]) -> dict[str, object]:
    context_counts: dict[str, int] = {}
    trigram_counts: dict[str, int] = {}

    for word in words:
        padded = f"^^{word}$"
        for index in range(len(padded) - 2):
            context = padded[index:index + 2]
            trigram = padded[index:index + 3]
            context_counts[context] = context_counts.get(context, 0) + 1
            trigram_counts[trigram] = trigram_counts.get(trigram, 0) + 1

    return {
        "version": 1,
        "alphabetSize": 28,
        "wordCount": len(words),
        "contexts": context_counts,
        "trigrams": trigram_counts,
    }


